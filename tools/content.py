#!/usr/bin/env python3
"""Read the content that staff edit in the admin panel (content/) and write the data files the site uses.

content/articles/*.md   -> articles.js   (one Markdown file per article, settings at the top)
content/services.json   -> services.js
content/promos.json     -> promos.js

articles.js, services.js and promos.js are generated: edit content/ instead.
"""
import datetime, html, json, os, re

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
e = html.escape
HEADER = "/* Generated by tools/content.py from the content/ folder. Edit the content in the admin panel, not here. */\n"
DEFAULT_EMOJI = ["📣", "💬", "📈"]


def bi(s):
    # The site is Khmer only; the data keeps the kh/en shape the page scripts expect.
    s = "" if s is None else str(s).strip()
    return {"kh": s, "en": s}


def emoji_list(v):
    if isinstance(v, list): parts = [str(x).strip() for x in v if str(x).strip()]
    else: parts = str(v or "").split()
    return parts[:3] if len(parts) >= 3 else DEFAULT_EMOJI


def asset(p):
    # Uploaded files are saved as /assets/uploads/...; the page scripts use paths without the leading slash.
    p = str(p or "").strip()
    return p.lstrip("/") if p else ""


def read_front_matter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.S)
    if not m: return {}, text
    return yaml.safe_load(m.group(1)) or {}, m.group(2)


def inline(s):
    s = e(s, quote=False)
    s = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)\)", lambda m: f'<img src="{e(m.group(2))}" alt="{e(m.group(1))}" loading="lazy">', s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{e(m.group(2))}" target="_blank" rel="noopener">{m.group(1)}</a>', s)
    s = re.sub(r"\*\*(.+?)\*\*|__(.+?)__", lambda m: f"<strong>{m.group(1) or m.group(2)}</strong>", s)
    s = re.sub(r"(?<![\*\w])\*(?!\s)(.+?)(?<!\s)\*(?!\*)", r"<em>\1</em>", s)
    return s


def md_to_html(text):
    """Small Markdown converter for article bodies: headings, paragraphs, lists, quotes, images, bold, italic, links.
    If the body is already HTML it is used as is."""
    text = (text or "").strip()
    if text.startswith("<"): return text
    out = []
    for block in re.split(r"\n\s*\n", text):
        lines = [l.rstrip() for l in block.strip().split("\n") if l.strip()]
        if not lines: continue
        first = lines[0]
        h = re.match(r"^(#{1,6})\s+(.*)$", first)
        if h and len(lines) == 1:
            level = 2 if len(h.group(1)) <= 2 else 3
            out.append(f"<h{level}>{inline(h.group(2))}</h{level}>")
        elif all(re.match(r"^\s*[-*+]\s+", l) for l in lines):
            out.append("<ul>" + "".join(f"<li>{inline(re.sub(r'^\s*[-*+]\s+', '', l))}</li>" for l in lines) + "</ul>")
        elif all(re.match(r"^\s*\d+[.)]\s+", l) for l in lines):
            out.append("<ol>" + "".join(f"<li>{inline(re.sub(r'^\s*\d+[.)]\s+', '', l))}</li>" for l in lines) + "</ol>")
        elif all(l.startswith(">") for l in lines):
            out.append("<blockquote><p>" + "<br>".join(inline(l.lstrip("> ")) for l in lines) + "</p></blockquote>")
        elif len(lines) == 1 and re.fullmatch(r"!\[[^\]]*\]\([^)\s]+\)", first.strip()):
            out.append(f"<figure>{inline(first.strip())}</figure>")
        else:
            if h:  # heading followed by text in the same block
                level = 2 if len(h.group(1)) <= 2 else 3
                out.append(f"<h{level}>{inline(h.group(2))}</h{level}>")
                lines = lines[1:]
            out.append("<p>" + "<br>".join(inline(l) for l in lines) + "</p>")
    return "\n".join(out)


def load_articles():
    folder = os.path.join(ROOT, "content", "articles")
    arts = []
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".md"): continue
        fm, body = read_front_matter(os.path.join(folder, name))
        if fm.get("draft"): continue
        d = fm.get("date") or datetime.date.today()
        d = d.isoformat()[:10] if hasattr(d, "isoformat") else str(d)[:10]
        arts.append({
            "id": name[:-3],
            "date": d,
            "tag": bi(fm.get("tag") or "ចំណេះដឹង"),
            "title": bi(fm.get("title") or name[:-3]),
            "summary": bi(fm.get("summary") or ""),
            "emoji": emoji_list(fm.get("emoji")),
            "cover": asset(fm.get("cover")),
            "html": md_to_html(body),
            # SEO fields (filled in by the auto-publisher; optional for hand-written articles)
            "seo_title": str(fm.get("seo_title") or "").strip(),
            "seo_description": str(fm.get("seo_description") or "").strip(),
            "keywords": [str(k).strip() for k in (fm.get("keywords") or []) if str(k).strip()] if isinstance(fm.get("keywords"), list) else [],
            "category": str(fm.get("category") or "").strip(),
            "image_alt": str(fm.get("image_alt") or "").strip(),
            "modified": (fm.get("updated").isoformat()[:10] if hasattr(fm.get("updated"), "isoformat") else str(fm.get("updated") or "")[:10]) or None,
        })
    return sorted(arts, key=lambda a: a["date"], reverse=True)


def load_services():
    data = json.load(open(os.path.join(ROOT, "content", "services.json"), encoding="utf-8"))
    groups = []
    for g in data.get("groups", []):
        svcs = []
        for s in g.get("services", []):
            item = {"id": s["id"], "emoji": emoji_list(s.get("emoji")), "name": bi(s.get("name")), "desc": bi(s.get("desc")),
                    "price": str(s.get("price") or "").strip()}
            if s.get("popular"): item["popular"] = True
            if s.get("poster"): item["poster"] = asset(s["poster"])
            if s.get("thumb"): item["thumb"] = optimized(asset(s["thumb"]), (960, 540))
            svcs.append(item)
        groups.append({"id": g["id"], "name": bi(g.get("name")), "services": svcs})
    return groups


def load_promos():
    data = json.load(open(os.path.join(ROOT, "content", "promos.json"), encoding="utf-8"))
    promos = []
    for p in data:
        img = asset(p.get("image"))
        if not img: continue
        promos.append({"id": p.get("id") or re.sub(r"\W+", "-", os.path.basename(img)).strip("-"), "image": img, "thumb": img,
                       "badge": bi(p.get("badge")) if p.get("badge") else None, "title": bi(p.get("title")), "price": bi(p.get("price")),
                       "points": {"kh": [str(x) for x in p.get("points") or []], "en": [str(x) for x in p.get("points") or []]},
                       "popup": p.get("popup", True) is not False})
    return promos


def make_thumbs(promos):
    # Smaller copies of the promotion posters for cards; skipped if Pillow is missing.
    try:
        from PIL import Image
    except ImportError:
        return
    for p in promos:
        src = os.path.join(ROOT, p["image"])
        if not os.path.exists(src): continue
        base, _ = os.path.splitext(p["image"])
        thumb = base + "-sm.jpg"
        dst = os.path.join(ROOT, thumb)
        if not os.path.exists(dst):
            im = Image.open(src).convert("RGB"); im.thumbnail((540, 540)); im.save(dst, quality=80, optimize=True, progressive=True)
        p["thumb"] = thumb


OPT_DIR = os.path.join("assets", "opt")
_opt_used = set()


def optimized(rel, box):
    """A small, fast copy of an uploaded picture (WebP, fitted inside box), saved under assets/opt/.
    Staff upload any size in the admin panel; visitors get the small copy. Falls back to the original
    if Pillow is missing or the file can't be read."""
    if not rel: return rel
    src = os.path.join(ROOT, rel)
    try:
        from PIL import Image, ImageOps
        import hashlib
        with open(src, "rb") as f: digest = hashlib.md5(f.read() + repr(box).encode()).hexdigest()[:10]
        stem = re.sub(r"[^a-z0-9]+", "-", os.path.splitext(os.path.basename(rel))[0].lower()).strip("-") or "img"
        out = os.path.join(OPT_DIR, f"{stem}-{digest}.webp")
        _opt_used.add(out)
        dst = os.path.join(ROOT, out)
        if not os.path.exists(dst):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            im = ImageOps.exif_transpose(Image.open(src))
            im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
            im.thumbnail(box, Image.LANCZOS)
            im.save(dst, "WEBP", quality=82, method=6)
        return out.replace(os.sep, "/")
    except Exception as ex:
        print(f"Warning: could not optimise {rel}: {ex}")
        return rel


def load_clients():
    """content/clients.json -> the client logo strip on the home page (edited in the admin panel)."""
    path = os.path.join(ROOT, "content", "clients.json")
    if not os.path.exists(path): return []
    with open(path, encoding="utf-8") as f: data = json.load(f)
    out = []
    for c in data.get("clients", []):
        logo = asset(c.get("logo"))
        if not logo or not os.path.exists(os.path.join(ROOT, logo)): continue
        out.append({"name": str(c.get("name") or "").strip(), "logo": optimized(logo, (256, 256))})
    return out


def clean_opt():
    """Remove optimised copies that nothing uses any more."""
    folder = os.path.join(ROOT, OPT_DIR)
    if not os.path.isdir(folder): return
    for name in os.listdir(folder):
        if os.path.join(OPT_DIR, name) not in _opt_used: os.remove(os.path.join(folder, name))


def js(name, value):
    return HEADER + f"window.{name} = " + json.dumps(value, ensure_ascii=False, indent=1) + ";\n"


def write_all():
    arts = load_articles()
    services = load_services()
    promos = load_promos()
    clients = load_clients()
    import accounts
    accts = accounts.load(asset, optimized)
    make_thumbs(promos)
    clean_opt()
    listing = [{k: a[k] for k in ("id", "date", "tag", "title", "summary", "emoji", "cover") if a.get(k)} for a in arts]
    for path, text in (("articles.js", js("ARTICLES", listing)), ("services.js", js("SERVICE_GROUPS", services)), ("promos.js", js("PROMOS", promos)), ("clients.js", js("CLIENTS", clients)), ("accounts.js", js("ACCOUNTS", accts))):
        with open(os.path.join(ROOT, path), "w", encoding="utf-8") as f: f.write(text)
    return arts, services, promos


if __name__ == "__main__":
    a, s, p = write_all()
    print(f"Content: {len(a)} articles, {sum(len(g['services']) for g in s)} services, {len(p)} promotions")
